"""Import source-linked paper answers, sections and explicit scoring references."""

import argparse
import hashlib
import json
import re
from pathlib import Path

from pypdf import PdfReader
from paper_sources import (answer_groups, booklet_boundaries, booklet_sections,
                           normalize_text, ocr_page, page_text, reading_lines,
                           source_hash, text_pages)

ROOT = Path(__file__).resolve().parents[1]
# 原脚本的扁平目录已被按机构整理；保留旧卷 ID 和字节一致的生成数据，避免历史草稿失联。
RAW = ROOT / '.raw'
SOURCE = RAW / '花生' / '2026下半年一期花生十三行测套题' / '答案'
TARGET = ROOT / 'src' / 'data' / 'papers.js'
BOOKLETS = SOURCE.parent / '题本'
CATALOG = ROOT / 'src' / 'data' / 'imported-papers.js'
EVIDENCE = ROOT / 'data' / 'paper-import-verification.json'
MODULE_RANGES = [(1, 20), (21, 35), (36, 65), (66, 75), (76, 110), (111, 130)]


def generate():
    papers = []
    # Bind the OCR boundary evidence to the actual booklet bytes, so changed PDFs cannot reuse stale mappings.
    booklets = json.loads((ROOT / 'data' / 'booklet-verification.json').read_text())
    if [item['number'] for item in booklets] != list(range(1, 13)):
        raise ValueError('Booklet verification must cover all 12 papers')
    files = sorted(SOURCE.glob('*.pdf'), key=lambda p: int(re.search(r'(\d+)\.pdf$', p.name)[1]))
    if len(files) != 12:
        raise ValueError(f'Expected 12 PDFs, found {len(files)}')
    for number, file in enumerate(files, 1):
        if int(re.search(r'(\d+)\.pdf$', file.name)[1]) != number:
            raise ValueError(f'Missing or duplicate paper number: {file.name}')
        reader = PdfReader(file)
        booklet = booklets[number - 1]
        booklet_hash = hashlib.sha256((BOOKLETS / booklet['sourceFile']).read_bytes()).hexdigest()
        if booklet_hash != booklet['sourceSha256']:
            raise ValueError(f'Booklet changed; verify question types again: {booklet["sourceFile"]}')
        if [(item['start'], item['end']) for item in booklet['reasoningBoundaries']] != [(76, 85), (86, 95), (96, 100), (101, 110)]:
            raise ValueError(f'Unexpected reasoning ranges in booklet {number}')
        text = '\n'.join(page.extract_text() or '' for page in reader.pages)
        groups = re.findall(r'(\d+)\s*--?\s*(\d+)\s+([A-D]{5})\b', text)
        expected = [(str(i), str(i + 4)) for i in range(1, 131, 5)]
        if [(start, end) for start, end, _ in groups] != expected:
            raise ValueError(f'Incomplete, duplicate or unordered answers: {file.name}')
        for start, end in MODULE_RANGES:
            if not re.search(rf'[（(]\s*{start}\s*--?\s*{end}\s*[）)]', text):
                raise ValueError(f'Missing section {start}-{end}: {file.name}')
        papers.append({
            'id': f'sihai-2026-h2-{number:02d}',
            **verified_time_limit(f'sihai-2026-h2-{number:02d}', booklet_hash),
            'number': number,
            'title': f'四海 · 第 {number:02d} 套',
            'sourceFile': file.name,
            'sourceSha256': hashlib.sha256(file.read_bytes()).hexdigest(),
            'bookletFile': booklet['sourceFile'],
            'bookletSha256': booklet_hash,
            'reasoningBoundaries': booklet['reasoningBoundaries'],
            'answerKey': ''.join(answers for _, _, answers in groups),
        })
    return '// Generated by scripts/import-papers.py. Each key is verified against its source PDF.\nexport const PAPERS = ' + json.dumps(papers, ensure_ascii=False, indent=2) + ';\n'


# 时限只来自逐卷核对的卷首清单，未核实的新卷不继承旧卷的120分钟。
def verified_time_limit(paper_id, booklet_hash):
    entries = json.loads((ROOT / 'data/booklet-time-limits.json').read_text())['entries']
    record = next((item for item in entries if item['paperId'] == paper_id), None)
    if record is None:
        return {}
    if record['sha256'] != booklet_hash:
        raise ValueError(f'Booklet time-limit evidence changed: {paper_id}')
    return {'timeLimitMinutes': record['minutes'], 'timeLimitKind': record['kind'],
            'timeLimitSource': {'file': record['file'], 'sha256': booklet_hash, 'pdfPage': record['pdfPage']}}


def one_file(folder, pattern, number):
    matches = [p for p in folder.glob('*.pdf')
               if (m := re.search(pattern, p.name)) and int(m[1]) == number]
    if len(matches) != 1:
        raise ValueError(f'Expected one source for paper {number} in {folder}, got {len(matches)}')
    return matches[0]


def complete_groups(text, count):
    groups, missing, bad = answer_groups(text, count)
    if missing:
        raise ValueError(f'Incomplete answer ranges: {missing}; unreadable: {bad}')
    return ''.join(groups[n] for n in range(1, count + 1, 5))


def checked_source(path, pages=None):
    result = {'file': str(path.relative_to(RAW)), 'sha256': source_hash(path)}
    if pages is not None:
        result['pdfPages'] = pages
    return result


def reference_sections(booklet, count, rule):
    sections = booklet_sections(booklet, count)
    for section in sections:
        section['cents'] = rule['weights'][section['id']]
    return sections


def make_paper(paper_id, number, title, institution, project, period, variant,
               key, sections, answers, booklet, scoring_rule, supplements=None):
    occupied = [q for s in sections for q in range(s['start'], s['end'] + 1)]
    if occupied != list(range(1, len(key) + 1)) or not re.fullmatch('[ABCD]+', key):
        raise ValueError(f'Question coverage or answer key is invalid: {title}')
    return {'id': paper_id, **verified_time_limit(paper_id, source_hash(booklet)), 'number': number, 'title': title,
            'institution': institution, 'project': project, 'period': period,
            'variant': variant, 'answerKey': key, 'questionCount': len(key),
            'sections': sections, 'scoringRule': scoring_rule,
            'sources': {'answers': answers, 'booklet': checked_source(booklet)},
            'supplements': supplements or []}


def additional_papers():
    config = json.loads((ROOT / 'data/paper-import-config.json').read_text())
    review = json.loads((ROOT / 'data/paper-ocr-review.json').read_text())
    result = []
    base = RAW / '花生' / '2026下半年二期花生十三行测套题'
    for variant, code in [('地市', 'city'), ('副省', 'province')]:
        profile = config['publisherProfiles'][variant]
        if source_hash(RAW / profile['sourceFile']) != profile['sourceSha256']:
            raise ValueError(f'Scoring image changed; review it before import: {variant}')
        count = profile['sections'][-1]['end']
        for number in range(1, 13):
            answer = one_file(base / variant / '答案', r'行测(\d+)', number)
            booklet = one_file(base / variant / '题本', r'[（(](\d+)[）)]', number)
            pages = text_pages(answer)
            # 差异题可能印在主答案同一页，也可能跨页；按标题分段，不能只截第一页。
            combined = '\n\f\n'.join(pages)
            parts = combined.split('差异题', 1)
            key = complete_groups(parts[0], count)
            boundaries = booklet_boundaries(booklet, variant == '副省')
            sections = [dict(s) for s in profile['sections']]
            for section in sections:
                hit = next((b for b in boundaries if b['name'] == section['name']), None)
                if hit:
                    if hit['start'] != section['start']:
                        raise ValueError(f'Scoring ranges differ from booklet: {booklet.name}')
                    section['pdfPage'] = hit['pdfPage']
            supplements = []
            if len(parts) == 2:
                supplement_count = max(int(n) for n in re.findall(r'--?\s*(\d+)', parts[1]))
                supplements.append({'label': '差异题', 'answerKey': complete_groups(parts[1], supplement_count),
                                    'pdfPage': parts[0].count('\f') + 1})
            scoring = {'kind': 'publisher', 'id': f'sihai-h2-p2-{code}',
                       'label': '按本套卷随附分值表计分',
                       'source': {'file': profile['sourceFile'], 'sha256': profile['sourceSha256']}}
            result.append(make_paper(f'sihai-2026-h2-p2-{code}-{number:02d}', number,
                f'花生十三 · 二期{variant} · 第 {number:02d} 套', '四海',
                '2026 下半年 · 国考行测', '二期', '副省级' if variant == '副省' else '地市级 / 行政执法类',
                key, sections, checked_source(answer, [1]), booklet, scoring, supplements))

    rule = config['referenceRule']
    reference = {'kind': 'reference', 'id': rule['id'], 'label': rule['label'],
                 'normalizationMaxCents': rule['normalizationMaxCents'],
                 'rounding': 'half-up-after-total',
                 'note': '采用平台国考练习参考权重，按本卷总权重折算至100分，不代表官方逐题分值。'}
    base = RAW / '超格' / '2027超格公考10套卷'
    answer = next((base / '答案').glob('*.pdf'))
    for number in range(1, 11):
        page = number + 1
        chinese = '\n'.join(reading_lines(ocr_page(answer, page, scale=3)))
        english = '\n'.join(reading_lines(ocr_page(answer, page, scale=3, english=True)))
        # 前六卷的5道附加题独立编号，后四卷为120题；不能把附加答案覆盖主卷前5题。
        main, *appendix = chinese.split('附加题')
        count = max(int(n) for n in re.findall(r'[-—–~～]+\s*(\d+)\s*[:：]', main))
        key = complete_groups(main, count)
        if appendix:
            resets = list(re.finditer(r'(?:^|\n)1\s*[~—–-]+\s*5\s*:', english))
            if len(resets) == 2:
                english = english[:resets[-1].start()]
        other, _, _ = answer_groups(english, count)
        for start, group in other.items():
            if key[start - 1:start + 4] != group:
                raise ValueError(f'OCR disagreement in chaoge paper {number}, questions {start}-{start+4}')
        booklet = one_file(base / '题本', r'套卷(\d+)_', number)
        supplements = [{'label': '附加题', 'answerKey': complete_groups(appendix[0], 5),
                        'pdfPage': page + 1}] if appendix else []
        result.append(make_paper(f'chaoge-2027-{number:02d}', number,
            f'超格 · 2027 公考 · 第 {number:02d} 套', '超格', '2027 公考 · 行测',
            '10套卷', f'{count}题版', key, reference_sections(booklet, count, rule),
            checked_source(answer, [page + 1]), booklet, reference, supplements))

    base = RAW / '粉笔' / '2027国考极致模考6套卷'
    source = review['fenbi']
    answer = RAW / source['sourceFile']
    if source_hash(answer) != source['sourceSha256']:
        raise ValueError('Fenbi PDF differs from visually reviewed answer tables')
    numerals = '一二三四五六'
    for item in source['papers']:
        number = item['number']
        key = ''.join(item['groups'])
        page = item['pdfPage'] - 1
        text = '\n'.join(reading_lines(ocr_page(answer, page, scale=3))).split('答案梳理')[0]
        recognized, _, _ = answer_groups(text, 130)
        if any(key[start - 1:start + 4] != group for start, group in recognized.items()):
            raise ValueError(f'Fenbi visual review conflicts with OCR: paper {number}')
        matches = [p for p in (base / '题本').glob('*.pdf') if numerals[number - 1] in p.stem]
        if len(matches) != 1:
            raise ValueError(f'Fenbi booklet is ambiguous: {number}')
        booklet = matches[0]
        result.append(make_paper(f'fenbi-2027-guokao-{number:02d}', number,
            f'粉笔 · 国考极致模考 · 第 {number:02d} 套', '粉笔', '2027 国考 · 行测',
            '极致模考6套卷', '130题版', key, reference_sections(booklet, 130, rule),
            checked_source(answer, [page + 1]), booklet, reference))

    base = RAW / '上岸村' / '2027上岸村公考10套卷'
    for number in range(1, 11):
        answer = one_file(base / '答案', r'【(\d+)】', number)
        booklet = one_file(base / '题本', r'【(\d+)】', number)
        found = {}
        source_pages = set()
        for page in range(len(text_pages(answer))):
            text = normalize_text(page_text(answer, page, scale=2.2))
            pattern = r'(?:^|\n)[^\d\n]{0,4}(\d{1,3})\s*[.、．]?\s*[【\[]\s*答案\s*[】\]]\s*[:：]?\s*([ABCD])'
            for match in re.finditer(pattern, text):
                q = int(match[1])
                if q in found:
                    raise ValueError(f'Duplicate answer heading: {answer.name}, question {q}')
                found[q] = match[2]
                source_pages.add(page + 1)
        for correction in review['answerOverrides']:
            if correction['sourceFile'] != str(answer.relative_to(RAW)):
                continue
            if source_hash(answer) != correction['sourceSha256']:
                raise ValueError('Answer correction evidence is stale')
            question = correction['question']
            if question in found and found[question] != correction['answer']:
                raise ValueError('Reviewed answer conflicts with source')
            found[question] = correction['answer']
            source_pages.add(correction['evidencePage'])
        count = max(found)
        if set(found) != set(range(1, count + 1)):
            raise ValueError(f'Missing answers in {answer.name}: {sorted(set(range(1,count+1))-set(found))}')
        key = ''.join(found[n] for n in range(1, count + 1))
        label = re.sub(r'^【\d+】|[-－]解析(?:[-－]新)?$', '', answer.stem)
        result.append(make_paper(f'shangancun-2027-{number:02d}', number,
            f'上岸村 · {label}', '上岸村', '2027 公考 · 行测', '公考10套卷', f'{count}题版',
            key, reference_sections(booklet, count, rule), checked_source(answer, sorted(source_pages)),
            booklet, reference))
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify the tracked answer keys without changing them')
    args = parser.parse_args()
    result = generate()
    imported = additional_papers()
    catalog_text = '// Generated by scripts/import-papers.py; private answer data, never serve to browsers.\nexport const IMPORTED_PAPERS = ' + json.dumps(imported, ensure_ascii=False, indent=2) + ';\n'
    evidence = {'legacyPapers': 12, 'importedPapers': len(imported),
                'mainAnswerCount': 1560 + sum(p['questionCount'] for p in imported),
                'supplementalAnswerCount': sum(len(s['answerKey']) for p in imported for s in p['supplements']),
                'papers': [{k: p[k] for k in ['id','questionCount','sources','scoringRule']}
                           for p in imported]}
    evidence_text = json.dumps(evidence, ensure_ascii=False, indent=2) + '\n'
    if args.check:
        for path, expected in [(TARGET, result), (CATALOG, catalog_text), (EVIDENCE, evidence_text)]:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f'Generated data differs from source evidence: {path.relative_to(ROOT)}')
        print(f'Verified {12+len(imported)} papers / {evidence["mainAnswerCount"]} main answers against source evidence.')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(result)
        CATALOG.write_text(catalog_text)
        EVIDENCE.write_text(evidence_text)
        print(f'Imported {len(imported)} new papers; preserved 12 legacy papers; {evidence["mainAnswerCount"]} main answers total.')
