import test from "node:test";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { createServer } from "node:net";
import { once } from "node:events";
import { mkdtemp, rm, mkdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { chromium } from "playwright";

test("timer and uncertainty controls remain usable on compact phones", { timeout: 60000 }, async t => {
  const directory = await mkdtemp(join(tmpdir(), "ios-timer-feedback-"));
  const reservation = createServer(); reservation.listen(0, "127.0.0.1"); await once(reservation, "listening");
  const port = reservation.address().port; await new Promise(done => reservation.close(done));
  const server = spawn(process.execPath, ["scripts/serve.mjs"], { env: { ...process.env, PORT: String(port), ROLLIERANK_DATA_DIR: directory }, stdio: ["ignore", "pipe", "pipe"] });
  let logs = "", browser;
  server.stdout.on("data", chunk => { logs += chunk; }); server.stderr.on("data", chunk => { logs += chunk; });
  t.after(async () => { await browser?.close(); server.kill("SIGTERM"); if (server.exitCode === null) await once(server, "exit"); await rm(directory, { recursive: true, force: true }); });
  await new Promise((done, reject) => { const timeout = setTimeout(() => reject(new Error(logs || "Service not ready")), 15000); server.stdout.on("data", () => { if (logs.includes("RollieRank is ready")) { clearTimeout(timeout); done(); } }); server.once("error", reject); });
  browser = await chromium.launch({ headless: true });
  const evidence = resolve("test-results/feedback-reaudit/timer-entry"); await mkdir(evidence, { recursive: true });
  const open = async session => {
    const page = await browser.newPage({ viewport: { width: 320, height: 568 }, reducedMotion: "reduce" });
    page.setDefaultTimeout(5000);
    await page.goto(`http://127.0.0.1:${port}/ios-v3/app.html?page=home&empty=1&session=feedback-${session}&design=paper-cards-1114-v3`, { waitUntil: "networkidle" });
    await page.getByRole("button", { name: "开始做题计时", exact: true }).click();
    assert.equal(await page.locator('.rr-timer-paper-list').getAttribute('data-picker-level'), "institution");
    await page.getByRole("button", { name: "选择花生计时套卷", exact: true }).click();
    await page.getByRole("button", { name: /选择花生一期/ }).click();
    await page.getByRole("button", { name: /花生，.*第 1 套，开始计时/ }).click();
    return page;
  };
  await t.test("source round trip keeps the selected paper, minutes and order", async () => {
    const page = await open("roundtrip");
    await page.getByRole("button", { name: "分模块", exact: true }).click();
    await page.getByRole("spinbutton", { name: "政治理论计划分钟", exact: true }).fill("13");
    await page.getByRole("spinbutton", { name: "常识判断计划分钟", exact: true }).fill("7");
    await page.getByRole("button", { name: "调整政治理论顺序", exact: true }).focus(); await page.keyboard.press("ArrowDown");
    const plan = await page.locator(".rr-timer-planned-module").allTextContents();
    await page.getByRole("tab", { name: "自定义", exact: true }).click();
    await page.getByRole("spinbutton", { name: "自定义总分钟", exact: true }).fill("45");
    await page.getByRole("tab", { name: "套卷", exact: true }).click();
    await page.screenshot({ path: join(evidence, "regression-paper-roundtrip.png") });
    assert.equal(await page.getByRole("button", { name: "更换计时套卷", exact: true }).count(), 1, "returning from custom timing must retain the selected paper");
    assert.deepEqual(await page.locator(".rr-timer-planned-module").allTextContents(), plan);
    assert.equal(await page.getByRole("spinbutton", { name: "政治理论计划分钟", exact: true }).inputValue(), "13");
    assert.equal(await page.getByRole("spinbutton", { name: "常识判断计划分钟", exact: true }).inputValue(), "7");
    await page.getByRole("tab", { name: "自定义", exact: true }).click();
    assert.equal(await page.getByRole("spinbutton", { name: "自定义总分钟", exact: true }).inputValue(), "45");
    await page.close();
  });
  await t.test("planning fields clear the action bar and starting reveals the clock", async () => {
    const page = await open("short");
    await page.getByRole("button", { name: "分模块", exact: true }).click();
    const visibleRows = await page.locator('.rr-timer-planned-module input').evaluateAll(inputs => { const footer = document.querySelector('.rr-timer-sticky-footer').getBoundingClientRect(); return inputs.filter(input => { const r = input.getBoundingClientRect(); return r.top >= 0 && r.bottom <= footer.top; }).length; });
    await page.screenshot({ path: join(evidence, "regression-module-top-320x568.png") });
    assert.ok(visibleRows >= 2, "expanded planning must expose at least two complete module fields on 320×568");
    // Native keyboard focus extends outside the handle; the scroll viewport must preserve that outline.
    const handle = page.getByRole("button", { name: "调整政治理论顺序", exact: true });
    await handle.focus(); await page.keyboard.press("ArrowDown");
    await handle.focus(); await page.keyboard.press("ArrowUp");
    const focusClearance = await handle.evaluate(element => { const field = element.getBoundingClientRect(), viewport = element.closest('.rr-timer-scroll-content').getBoundingClientRect(), style = getComputedStyle(element), inset = parseFloat(style.outlineWidth) + parseFloat(style.outlineOffset); return { left: field.left - inset - viewport.left, right: viewport.right - field.right - inset }; });
    assert.ok(focusClearance.left >= 0 && focusClearance.right >= 0, "keyboard focus outline must not be clipped by the scroll container");
    await page.setViewportSize({ width: 320, height: 330 });
    const last = page.getByRole("spinbutton", { name: "资料分析计划分钟", exact: true });
    await last.click();
    const field = await last.boundingBox(), footer = await page.locator('.rr-timer-sticky-footer').boundingBox();
    await page.screenshot({ path: join(evidence, "regression-keyboard-320x330.png") });
    assert.ok(field && footer && field.y + field.height <= footer.y - 2, "focused field must be completely above the action bar");
    await page.setViewportSize({ width: 320, height: 568 });
    await last.click();
    await page.getByRole("button", { name: "开始做题", exact: true }).click();
    const clock = page.locator('.rr-session-clock');
    await page.waitForFunction(() => { const r = document.querySelector('.rr-session-clock')?.getBoundingClientRect(); return r && r.top > 80 && r.bottom < innerHeight; });
    await page.screenshot({ path: join(evidence, "regression-running-clock-320x568.png") });
    assert.match(await clock.innerText(), /整卷计划 120 分钟/);
    assert.match(await clock.innerText(), /政治理论.*计划 12 分钟/s);
    await page.getByRole("button", { name: "暂停", exact: true }).click();
    await page.getByRole("button", { name: "资料分析", exact: true }).scrollIntoViewIfNeeded();
    await page.getByRole("button", { name: "继续", exact: true }).click();
    const resumed = await clock.boundingBox();
    assert.ok(resumed && resumed.y > 80 && resumed.y + resumed.height < 568, "resuming must reveal the elapsed clock");
    await page.close();
  });
  await t.test("visible uncertainty labels work in list and single modes", async () => {
    const page = await open("marks");
    await page.getByRole("button", { name: "开始做题", exact: true }).click();
    await page.getByRole("button", { name: "结束并录答", exact: true }).click();
    await page.locator('.view[data-page="entry"]').waitFor();
    assert.match(await page.locator('.entry-mark-button').first().innerText(), /存疑/);
    assert.match(await page.locator('.rr-entry-marks').innerText(), /待检查/);
    await page.locator('.entry-mark-button').first().click();
    assert.match(await page.locator('.entry-mark-button').first().innerText(), /已存疑/);
    await page.getByRole("button", { name: "切换单题模式", exact: true }).click();
    assert.match(await page.locator('.rr-single-mark').innerText(), /已存疑/);
    await page.getByRole("button", { name: "第 1 题，选 A", exact: true }).click();
    await page.locator('.rr-single-answer[data-single-question="2"]').waitFor();
    await page.getByRole("button", { name: "上一题", exact: true }).click();
    await page.getByRole("button", { name: "第 1 题，选 A", exact: true }).click();
    await page.locator('.rr-single-answer[data-single-question="2"]').waitFor();
    for (const [width, height] of [[320, 568], [390, 844], [430, 932]]) {
      await page.setViewportSize({ width, height });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
      await page.screenshot({ path: join(evidence, `regression-single-${width}x${height}.png`) });
    }
    await page.close();
  });
  await writeFile(join(evidence, "feedback-regressions-server.log"), logs);
});
